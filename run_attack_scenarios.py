"""
run_attack_scenarios.py

Generates a real dataset for the SentinelGate pipeline: realistic legitimate exam
traffic from one identity, and the four attack scenarios from the original audit
report from a *separate*, clearly-labeled identity -- so feature_engineering.py's
--attacker-users flag has clean ground truth to work with, instead of guessing.

Requires the stack to be up already:
    docker compose up --build

Usage:
    python run_attack_scenarios.py

Prints a running log of every call and its status. When it finishes, export and
run the pipeline exactly as before:
    curl http://localhost:8000/logs -H "Authorization: Bearer <teacher token>" -o gateway_logs_raw.json
    python -c "import pandas as pd, json; pd.DataFrame(json.load(open('gateway_logs_raw.json'))).to_csv('gateway_logs.csv', index=False)"
    python feature_engineering.py --input gateway_logs.csv --output features.csv --attacker-users attacker1
    python anomaly_detection.py --features features.csv --output metrics.json
"""

import random
import time

import requests

BASE = "http://localhost:8000"
TEACHER = {"username": "teacher1", "password": "password1"}
STUDENT = {"username": "student1", "password": "password2"}
ATTACKER = {"username": "attacker1", "password": "attackerpass123", "role": "student"}


def signup(user):
    r = requests.post(f"{BASE}/auth/signup", json={
        "username": user["username"], "password": user["password"], "role": user.get("role", "student"),
    })
    if r.status_code not in (200, 400):  # 400 = already exists, fine
        r.raise_for_status()


def login(user):
    r = requests.post(f"{BASE}/auth/login", json={"username": user["username"], "password": user["password"]})
    r.raise_for_status()
    return r.json()["access_token"]


def call(method, path, token=None, json_body=None, expect=None, label=""):
    headers = {"Authorization": f"Bearer {token}"} if token else {}
    try:
        r = requests.request(method, f"{BASE}{path}", headers=headers, json=json_body, timeout=5)
    except requests.RequestException as exc:
        print(f"[{label or path}] {method} {path} -> ERROR ({exc})")
        return None
    tag = "" if expect is None else (" [expected]" if r.status_code == expect else " [UNEXPECTED]")
    print(f"[{label or path}] {method} {path} -> {r.status_code}{tag}")
    return r


def setup_exam(teacher_token) -> int:
    print("\n--- Setup: teacher creates an exam with 3 MCQs ---")
    r = call("POST", "/exams", token=teacher_token, json_body={
        "title": "SentinelGate Test Exam", "description": "generated by run_attack_scenarios.py",
        "total_marks": 30, "duration_minutes": 30,
    }, label="setup: create exam")
    exam_id = r.json()["id"]

    for i in range(3):
        call("POST", "/questions/add-mcq", token=teacher_token, json_body={
            "exam_id": exam_id, "question_text": f"Sample question {i+1}?",
            "option_a": "A", "option_b": "B", "option_c": "C", "option_d": "D",
            "correct_answer": "A",
        }, label=f"setup: add MCQ {i+1}")
    return exam_id


def generate_legitimate_traffic(student_token, teacher_token, exam_id, rounds=20):
    print(f"\n--- Legitimate traffic: {rounds} rounds as student1 (and a few teacher actions) ---")
    for i in range(rounds):
        call("GET", "/exams", token=student_token, label="legit: list exams")
        time.sleep(random.uniform(0.4, 1.5))
        call("GET", f"/questions/{exam_id}", token=student_token, label="legit: view questions")
        time.sleep(random.uniform(0.4, 1.5))
        call("POST", "/submit-answer", token=student_token, json_body={
            "student_id": "student1", "exam_id": str(exam_id),
            "question_id": str((i % 3) + 1), "answer": "A",
        }, label="legit: submit answer")
        time.sleep(random.uniform(0.8, 2.5))

    # A few legitimate teacher actions interleaved in
    call("POST", "/evaluate", token=teacher_token, json_body={"student_id": "student1", "exam_id": str(exam_id)}, label="legit: teacher evaluates")
    time.sleep(0.5)
    call("POST", "/publish-result", token=teacher_token, json_body={"student_id": "student1", "exam_id": str(exam_id)}, label="legit: teacher publishes result")
    time.sleep(0.5)
    call("GET", "/results/student1", token=student_token, label="legit: student views own result")


def attack_privilege_escalation(attacker_token, exam_id, attempts=15):
    print("\n--- Attack 1: Privilege escalation (student calling teacher-only routes) ---")
    for _ in range(attempts):
        call("POST", "/evaluate", token=attacker_token, expect=403,
             json_body={"student_id": "attacker1", "exam_id": str(exam_id)}, label="attack: evaluate as student")
        call("POST", "/publish-result", token=attacker_token, expect=403,
             json_body={"student_id": "attacker1", "exam_id": str(exam_id)}, label="attack: publish-result as student")
        time.sleep(0.2)


def attack_cross_student_idor(attacker_token, victims=("student1", "teacher1", "nonexistent_user")):
    print("\n--- Attack 2: Cross-student IDOR (reading other identities' data) ---")
    for victim in victims:
        call("GET", f"/submissions/{victim}", token=attacker_token, expect=403, label=f"attack: read {victim}'s submissions")
        call("GET", f"/results/{victim}", token=attacker_token, expect=403, label=f"attack: read {victim}'s results")
        call("GET", f"/logs/{victim}", token=attacker_token, expect=403, label=f"attack: read {victim}'s logs")
        time.sleep(0.2)


def attack_route_probing(attacker_token, exam_id, victims=("student1", "teacher1")):
    print("\n--- Attack 3: Rapid route probing / lateral movement ---")
    routes = (
        [("GET", f"/questions/{exam_id}"), ("GET", "/exams"), ("GET", "/logs")]
        + [("GET", f"/logs/{v}") for v in victims]
        + [("GET", f"/submissions/{v}") for v in victims]
        + [("GET", f"/results/{v}") for v in victims]
    )
    for method, path in routes:
        call(method, path, token=attacker_token, label="attack: route probe")
        time.sleep(0.15)


def attack_direct_bypass():
    print("\n--- Attack 4: Direct service bypass (should now fail at the network level) ---")
    targets = [(5004, "/submissions/student1"), (5003, "/logs"), (5001, "/questions/1")]
    for port, path in targets:
        try:
            r = requests.get(f"http://localhost:{port}{path}", timeout=3)
            print(f"[direct bypass] port {port}{path} -> {r.status_code}  (REACHABLE -- network isolation NOT in effect)")
        except requests.exceptions.ConnectionError:
            print(f"[direct bypass] port {port}{path} -> connection refused  (network isolation working as intended)")


def main():
    print("=== Checking gateway is up ===")
    call("GET", "/health")

    signup(ATTACKER)

    teacher_token = login(TEACHER)
    student_token = login(STUDENT)
    attacker_token = login(ATTACKER)

    exam_id = setup_exam(teacher_token)

    generate_legitimate_traffic(student_token, teacher_token, exam_id, rounds=20)

    attack_privilege_escalation(attacker_token, exam_id, attempts=15)
    attack_cross_student_idor(attacker_token)
    attack_route_probing(attacker_token, exam_id)
    attack_direct_bypass()

    print(
        "\n=== Done. Export logs as teacher1 and re-run the pipeline with "
        "--attacker-users attacker1 to see real Precision/Recall/F1 numbers. ==="
    )


if __name__ == "__main__":
    main()
